export type Language = keyof typeof translations;

export function getTranslation(lang: Language, key: keyof typeof translations.en): string | readonly string[] {
  return translations[lang][key] || translations.en[key];
}

export function getInitialLanguage(): Language {
  if (typeof window === 'undefined') return 'en';
  
  // 首先检查本地存储
  const saved = localStorage.getItem('language') as Language;
  if (saved && (Object.keys(translations) as Language[]).includes(saved)) {
    return saved;
  }
  
  // 如果没有保存的语言，检查浏览器语言
  const browserLang = navigator.language;
  return detectLanguage(browserLang);
}

export function saveLanguage(language: Language) {
  if (typeof window !== 'undefined') {
    localStorage.setItem('language', language);
  }
}

export function detectLanguage(browserLang: string): Language {
  const langCode = browserLang.split('-')[0].toLowerCase();
  
  // 支持的语言映射
  const languageMap: { [key: string]: Language } = {
    'zh': 'zh',
    'es': 'es',
    'fr': 'fr',
    'de': 'de',
    'ja': 'ja',
    'ko': 'ko',
    'pt': 'pt',
    'ru': 'ru',
    'ar': 'ar',
    'hi': 'hi',
    'it': 'it',
    'nl': 'nl',
    'tr': 'tr',
    'sv': 'sv',
    'pl': 'pl',
    'da': 'da',
    'no': 'no',
    'fi': 'fi',
  };

  return languageMap[langCode] || 'en';
}

